--  migrations/006_CUSTOMER_LINES.sql  (TASKS P1-03: customer areas, security deposits, bank accounts)
--  Lines are added and deactivated, never deleted (BUSINESS_RULES §1). CUSTOMER_AREA and
--  SECURITY_DEPOSIT have no key, so they get a technical LINE_ID (SEQ_CUSTOMER_LINE; legacy rows are
--  numbered once here). CUSTOMER_AREA.GEO_CODE = the GEO_HIERARCHY city the line points to: filled
--  for Hattar legacy rows from LEGACY_MAP (ENTITY AREA, AREA_DOC); Karachi legacy rows use another
--  code set (zone/territory/area of the old rate geography) and keep their raw codes.
--  Oracle 11g compatible. Re-runnable: ORA-00955/01430/01408 are ignored, updates only touch empty values.
-- =====================================================================

CREATE SEQUENCE SEQ_CUSTOMER_LINE START WITH 1 NOCACHE;

ALTER TABLE CUSTOMER_AREA ADD (LINE_ID NUMBER, GEO_CODE VARCHAR2(50), ACTIVE CHAR(1) DEFAULT 'Y' NOT NULL, UPDATED_BY VARCHAR2(30), UPDATED_ON DATE);
UPDATE CUSTOMER_AREA SET LINE_ID = SEQ_CUSTOMER_LINE.NEXTVAL WHERE LINE_ID IS NULL;
UPDATE CUSTOMER_AREA a SET GEO_CODE = (SELECT MAX(m.NEW_CODE) FROM LEGACY_MAP m WHERE m.BRNCH = a.BRNCH AND m.ENTITY = 'AREA' AND m.LEGACY_CODE = TO_CHAR(a.AREA_DOC)) WHERE a.BRNCH = 2 AND a.GEO_CODE IS NULL;
CREATE UNIQUE INDEX UX_CUSTOMER_AREA_LINE ON CUSTOMER_AREA (LINE_ID);
CREATE INDEX IX_CUSTOMER_AREA_GEO ON CUSTOMER_AREA (BRNCH, CUST_ID, GEO_CODE);

ALTER TABLE SECURITY_DEPOSIT ADD (LINE_ID NUMBER, ACTIVE CHAR(1) DEFAULT 'Y' NOT NULL, UPDATED_BY VARCHAR2(30), UPDATED_ON DATE);
UPDATE SECURITY_DEPOSIT SET LINE_ID = SEQ_CUSTOMER_LINE.NEXTVAL WHERE LINE_ID IS NULL;
CREATE UNIQUE INDEX UX_SECURITY_DEPOSIT_LINE ON SECURITY_DEPOSIT (LINE_ID);
CREATE INDEX IX_SECURITY_DEPOSIT_CUST ON SECURITY_DEPOSIT (BRNCH, CUSTOMER_CODE);

ALTER TABLE CUSTOMER_BANK_ACC ADD (ACTIVE CHAR(1) DEFAULT 'Y' NOT NULL, UPDATED_BY VARCHAR2(30), UPDATED_ON DATE);
CREATE INDEX IX_CUSTOMER_BANK_ACC_CUST ON CUSTOMER_BANK_ACC (BRNCH, CUSTOMER_CODE);
