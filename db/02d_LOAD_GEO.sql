-- =====================================================================
--  02d_LOAD_GEO.sql   (run as SALES_NEW after migrations/002_GEO_HIERARCHY.sql)
--  Builds the unified geography Zone -> Territory -> Area -> City for both branches,
--  records every legacy code in LEGACY_MAP and places customers (decisions 19 Nov 2026).
--
--    Karachi  : Zone = MASTER_AREA, Territory = AREA, Area = DISTRICT, City = CITY (+ CITY_V_TAB extras)
--    Islamabad: Zone = copy of ZONE_DESC, Territory = ZONE_DESC, Area = TERRITORY, City = AREA
--
--  GEO_CODE = Z<zone>-T<territory>-A<area>-C<city> (cut at the node's level).
--  Customers:
--    Karachi  : city invoiced to most often in legacy invoice history SCLKHI.SD_SALES_VS_MRP
--               (city code; districts were renumbered over the years, city codes were not).
--    Islamabad: own zone/territory/area codes; area codes that do not exist (e.g. 21, 22)
--               -> placed on the territory level.
--    Customers whose GEO_SOURCE = 'MANUAL' are never overwritten.
--  Re-runnable: the tree and its LEGACY_MAP rows are rebuilt each time.
--  Reads the legacy schemas; legacy tables are not changed.
-- =====================================================================
SET DEFINE ON
SET VERIFY OFF
SET ECHO ON
SET TIMING ON
WHENEVER SQLERROR EXIT
SELECT CASE WHEN USER = 'SALES_NEW' THEN 'OK: connected as SALES_NEW' ELSE TO_CHAR(1/0) END AS user_check FROM dual;
WHENEVER SQLERROR CONTINUE
DEFINE KHI_SCH = SCLKHI

-- ---- 0. rebuild ---------------------------------------------------------------
DELETE FROM LEGACY_MAP WHERE ENTITY IN ('MASTER_AREA','AREA','DISTRICT','CITY','CITY_V_TAB','ZONE_DESC','TERRITORY');
DELETE FROM GEO_HIERARCHY;
COMMIT;

-- ---- 1. Karachi (BRNCH 1) -------------------------------------------------------
PROMPT KHI level 1 Zone <- MASTER_AREA
INSERT INTO GEO_HIERARCHY (GEO_ID, GEO_CODE, GEO_LEVEL, ZONE_CODE, ZONE_NAME, SOURCE_TABLE, LEGACY_CODE, BRNCH)
SELECT SEQ_GEO_HIERARCHY.NEXTVAL, 'Z' || m.M_AREA_CD, 1, TO_CHAR(m.M_AREA_CD), NVL(m.MASTER_AREA_NMAE, 'MASTER AREA ' || m.M_AREA_CD),
       'MASTER_AREA', TO_CHAR(m.M_AREA_CD), 1
  FROM MASTER_AREA m WHERE m.BRNCH = 1
  LOG ERRORS INTO ERR$_GEO_HIERARCHY ('KHI.MASTER_AREA') REJECT LIMIT UNLIMITED;

PROMPT KHI level 1 Zone <- AREA.M_AREA_CD values that are missing in MASTER_AREA (named after their area)
INSERT INTO GEO_HIERARCHY (GEO_ID, GEO_CODE, GEO_LEVEL, ZONE_CODE, ZONE_NAME, SOURCE_TABLE, LEGACY_CODE, REMARKS, BRNCH)
SELECT SEQ_GEO_HIERARCHY.NEXTVAL, 'Z' || x.M_AREA_CD, 1, TO_CHAR(x.M_AREA_CD), x.NAME, 'AREA', 'M' || x.M_AREA_CD,
       'Zone code not in MASTER_AREA; named after its only area - confirm with Sales', 1
  FROM (SELECT a.M_AREA_CD, MIN(a.AREA_NAME) NAME FROM AREA a
         WHERE a.BRNCH = 1 AND a.M_AREA_CD IS NOT NULL
           AND NOT EXISTS (SELECT 1 FROM MASTER_AREA m WHERE m.BRNCH = 1 AND m.M_AREA_CD = a.M_AREA_CD)
         GROUP BY a.M_AREA_CD) x
  LOG ERRORS INTO ERR$_GEO_HIERARCHY ('KHI.AREA.M_AREA_CD') REJECT LIMIT UNLIMITED;

PROMPT KHI level 2 Territory <- AREA
INSERT INTO GEO_HIERARCHY (GEO_ID, GEO_CODE, GEO_LEVEL, ZONE_CODE, ZONE_NAME, TERRITORY_CODE, TERRITORY_NAME, SOURCE_TABLE, LEGACY_CODE, BRNCH)
SELECT SEQ_GEO_HIERARCHY.NEXTVAL, z.GEO_CODE || '-T' || a.AREA_CD, 2, z.ZONE_CODE, z.ZONE_NAME, TO_CHAR(a.AREA_CD), a.AREA_NAME,
       'AREA', TO_CHAR(a.AREA_CD), 1
  FROM AREA a JOIN GEO_HIERARCHY z ON z.BRNCH = 1 AND z.GEO_LEVEL = 1 AND z.ZONE_CODE = TO_CHAR(a.M_AREA_CD)
 WHERE a.BRNCH = 1
  LOG ERRORS INTO ERR$_GEO_HIERARCHY ('KHI.AREA') REJECT LIMIT UNLIMITED;

PROMPT KHI level 3 Area <- DISTRICT
INSERT INTO GEO_HIERARCHY (GEO_ID, GEO_CODE, GEO_LEVEL, ZONE_CODE, ZONE_NAME, TERRITORY_CODE, TERRITORY_NAME, AREA_CODE, AREA_NAME, SOURCE_TABLE, LEGACY_CODE, BRNCH)
SELECT SEQ_GEO_HIERARCHY.NEXTVAL, t.GEO_CODE || '-A' || d.DIST_CD, 3, t.ZONE_CODE, t.ZONE_NAME, t.TERRITORY_CODE, t.TERRITORY_NAME,
       TO_CHAR(d.DIST_CD), NVL(d.DIST_NAME, 'DISTRICT ' || d.DIST_CD), 'DISTRICT', d.AREA_CD || '.' || d.DIST_CD, 1
  FROM DISTRICT d JOIN GEO_HIERARCHY t ON t.BRNCH = 1 AND t.GEO_LEVEL = 2 AND t.TERRITORY_CODE = TO_CHAR(d.AREA_CD)
 WHERE d.BRNCH = 1
  LOG ERRORS INTO ERR$_GEO_HIERARCHY ('KHI.DISTRICT') REJECT LIMIT UNLIMITED;

PROMPT KHI level 4 City <- CITY
INSERT INTO GEO_HIERARCHY (GEO_ID, GEO_CODE, GEO_LEVEL, ZONE_CODE, ZONE_NAME, TERRITORY_CODE, TERRITORY_NAME, AREA_CODE, AREA_NAME, CITY_CODE, CITY_NAME, SOURCE_TABLE, LEGACY_CODE, ACTIVE, BRNCH)
SELECT SEQ_GEO_HIERARCHY.NEXTVAL, a.GEO_CODE || '-C' || c.CITY_CD, 4, a.ZONE_CODE, a.ZONE_NAME, a.TERRITORY_CODE, a.TERRITORY_NAME,
       a.AREA_CODE, a.AREA_NAME, TO_CHAR(c.CITY_CD), NVL(c.CITY_NAME, 'CITY ' || c.CITY_CD), 'CITY', TO_CHAR(c.CITY_CD),
       CASE WHEN c.STATS = 'N' THEN 'N' ELSE 'Y' END, 1
  FROM CITY c JOIN GEO_HIERARCHY a ON a.BRNCH = 1 AND a.GEO_LEVEL = 3 AND a.LEGACY_CODE = c.AREA_CD || '.' || c.DIST_CD
 WHERE c.BRNCH = 1
  LOG ERRORS INTO ERR$_GEO_HIERARCHY ('KHI.CITY') REJECT LIMIT UNLIMITED;

PROMPT KHI level 4 City <- CITY_V_TAB cities that are not in CITY
INSERT INTO GEO_HIERARCHY (GEO_ID, GEO_CODE, GEO_LEVEL, ZONE_CODE, ZONE_NAME, TERRITORY_CODE, TERRITORY_NAME, AREA_CODE, AREA_NAME, CITY_CODE, CITY_NAME, SOURCE_TABLE, LEGACY_CODE, REMARKS, BRNCH)
SELECT SEQ_GEO_HIERARCHY.NEXTVAL, a.GEO_CODE || '-C' || v.CITY_CD, 4, a.ZONE_CODE, a.ZONE_NAME, a.TERRITORY_CODE, a.TERRITORY_NAME,
       a.AREA_CODE, a.AREA_NAME, TO_CHAR(v.CITY_CD), NVL(v.CITY_NAME, 'CITY ' || v.CITY_CD), 'CITY_V_TAB',
       v.AREA_CD || '.' || v.DIST_CD || '.' || v.CITY_CD, 'Only in CITY_V_TAB', 1
  FROM CITY_V_TAB v JOIN GEO_HIERARCHY a ON a.BRNCH = 1 AND a.GEO_LEVEL = 3 AND a.LEGACY_CODE = v.AREA_CD || '.' || v.DIST_CD
 WHERE v.BRNCH = 1
   AND NOT EXISTS (SELECT 1 FROM CITY c WHERE c.BRNCH = 1 AND c.AREA_CD = v.AREA_CD AND c.DIST_CD = v.DIST_CD AND c.CITY_CD = v.CITY_CD)
  LOG ERRORS INTO ERR$_GEO_HIERARCHY ('KHI.CITY_V_TAB') REJECT LIMIT UNLIMITED;
COMMIT;

-- ---- 2. Islamabad (BRNCH 2) ---------------------------------------------------
PROMPT ISB level 1 Zone <- ZONE_DESC (copy, as decided)
INSERT INTO GEO_HIERARCHY (GEO_ID, GEO_CODE, GEO_LEVEL, ZONE_CODE, ZONE_NAME, SOURCE_TABLE, LEGACY_CODE, REMARKS, BRNCH)
SELECT SEQ_GEO_HIERARCHY.NEXTVAL, 'Z' || z.ZONE_CODE, 1, z.ZONE_CODE, z.ZONE_NAME, 'ZONE_DESC', z.ZONE_CODE,
       'Islamabad zone level = copy of territory level (ISB has 3 levels)', 2
  FROM ZONE_DESC z WHERE z.BRNCH = 2
  LOG ERRORS INTO ERR$_GEO_HIERARCHY ('ISB.ZONE_DESC.L1') REJECT LIMIT UNLIMITED;

PROMPT ISB level 2 Territory <- ZONE_DESC
INSERT INTO GEO_HIERARCHY (GEO_ID, GEO_CODE, GEO_LEVEL, ZONE_CODE, ZONE_NAME, TERRITORY_CODE, TERRITORY_NAME, SOURCE_TABLE, LEGACY_CODE, BRNCH)
SELECT SEQ_GEO_HIERARCHY.NEXTVAL, z.GEO_CODE || '-T' || z.ZONE_CODE, 2, z.ZONE_CODE, z.ZONE_NAME, z.ZONE_CODE, z.ZONE_NAME,
       'ZONE_DESC', z.ZONE_CODE, 2
  FROM GEO_HIERARCHY z WHERE z.BRNCH = 2 AND z.GEO_LEVEL = 1
  LOG ERRORS INTO ERR$_GEO_HIERARCHY ('ISB.ZONE_DESC') REJECT LIMIT UNLIMITED;

PROMPT ISB level 3 Area <- TERRITORY
INSERT INTO GEO_HIERARCHY (GEO_ID, GEO_CODE, GEO_LEVEL, ZONE_CODE, ZONE_NAME, TERRITORY_CODE, TERRITORY_NAME, AREA_CODE, AREA_NAME, SOURCE_TABLE, LEGACY_CODE, BRNCH)
SELECT SEQ_GEO_HIERARCHY.NEXTVAL, t.GEO_CODE || '-A' || tr.TERRITORY_CODE, 3, t.ZONE_CODE, t.ZONE_NAME, t.TERRITORY_CODE, t.TERRITORY_NAME,
       tr.TERRITORY_CODE, tr.TERRITORY_DESC, 'TERRITORY', tr.ZONE_CODE || '.' || tr.TERRITORY_CODE, 2
  FROM TERRITORY tr JOIN GEO_HIERARCHY t ON t.BRNCH = 2 AND t.GEO_LEVEL = 2 AND t.TERRITORY_CODE = tr.ZONE_CODE
 WHERE tr.BRNCH = 2
  LOG ERRORS INTO ERR$_GEO_HIERARCHY ('ISB.TERRITORY') REJECT LIMIT UNLIMITED;

PROMPT ISB level 4 City <- AREA (code = AREA_DOC)
INSERT INTO GEO_HIERARCHY (GEO_ID, GEO_CODE, GEO_LEVEL, ZONE_CODE, ZONE_NAME, TERRITORY_CODE, TERRITORY_NAME, AREA_CODE, AREA_NAME, CITY_CODE, CITY_NAME, SOURCE_TABLE, LEGACY_CODE, BRNCH)
SELECT SEQ_GEO_HIERARCHY.NEXTVAL, a.GEO_CODE || '-C' || ar.AREA_DOC, 4, a.ZONE_CODE, a.ZONE_NAME, a.TERRITORY_CODE, a.TERRITORY_NAME,
       a.AREA_CODE, a.AREA_NAME, TO_CHAR(ar.AREA_DOC), NVL(ar.AREA_NAME, 'AREA ' || ar.AREA_DOC), 'AREA', TO_CHAR(ar.AREA_DOC), 2
  FROM AREA ar JOIN GEO_HIERARCHY a ON a.BRNCH = 2 AND a.GEO_LEVEL = 3 AND a.LEGACY_CODE = ar.ZONE_CODE || '.' || ar.TERRITORY_CODE
 WHERE ar.BRNCH = 2
  LOG ERRORS INTO ERR$_GEO_HIERARCHY ('ISB.AREA') REJECT LIMIT UNLIMITED;
COMMIT;

-- ---- 3. LEGACY_MAP: every legacy geography code -> new GEO_CODE ------------------
--  (the Islamabad level-1 copy is not mapped: ZONE_DESC maps to its territory node)
PROMPT LEGACY_MAP <- GEO_HIERARCHY
INSERT INTO LEGACY_MAP (BRNCH, ENTITY, LEGACY_CODE, NEW_CODE, SOURCE_DB, COMPC)
SELECT g.BRNCH, g.SOURCE_TABLE, g.LEGACY_CODE, g.GEO_CODE, CASE g.BRNCH WHEN 1 THEN 'SCLKHI' ELSE 'SCLISB' END, 1
  FROM GEO_HIERARCHY g
 WHERE NOT (g.BRNCH = 2 AND g.GEO_LEVEL = 1)
   AND NOT (g.BRNCH = 1 AND g.SOURCE_TABLE = 'AREA' AND g.GEO_LEVEL = 1);
COMMIT;

-- ---- 4. customers -------------------------------------------------------------
PROMPT KHI customers <- city invoiced to most often (SD_SALES_VS_MRP), ties -> latest DC date
MERGE INTO CUSTOMER_INFO c
USING (
  SELECT h.CUSTOMER_CODE, g.GEO_CODE
    FROM (SELECT s.CUSTOMER_CODE, s.CITY_CD,
                 ROW_NUMBER() OVER (PARTITION BY s.CUSTOMER_CODE ORDER BY COUNT(*) DESC, MAX(s.DC_DATE) DESC, s.CITY_CD) rn
            FROM &&KHI_SCH..SD_SALES_VS_MRP s
           WHERE s.CITY_CD IS NOT NULL
           GROUP BY s.CUSTOMER_CODE, s.CITY_CD) h
    JOIN (SELECT CITY_CODE, MIN(GEO_CODE) KEEP (DENSE_RANK FIRST ORDER BY CASE SOURCE_TABLE WHEN 'CITY' THEN 0 ELSE 1 END) GEO_CODE
            FROM GEO_HIERARCHY WHERE BRNCH = 1 AND GEO_LEVEL = 4 GROUP BY CITY_CODE) g
      ON g.CITY_CODE = TO_CHAR(h.CITY_CD)
   WHERE h.rn = 1) x
ON (c.BRNCH = 1 AND c.CUSTOMER_CODE = x.CUSTOMER_CODE)
WHEN MATCHED THEN UPDATE SET c.GEO_CODE = x.GEO_CODE, c.GEO_SOURCE = 'KHI_SALES_HISTORY'
 WHERE NVL(c.GEO_SOURCE, '-') <> 'MANUAL';

PROMPT ISB customers <- own area (zone + territory + area code)
MERGE INTO CUSTOMER_INFO c
USING (
  SELECT ci.CUSTOMER_CODE, g.GEO_CODE
    FROM CUSTOMER_INFO ci
    JOIN AREA ar ON ar.BRNCH = 2 AND ar.ZONE_CODE = ci.ZONE_CODE AND ar.TERRITORY_CODE = ci.TERRITORY_CODE
                AND REGEXP_LIKE(ci.AREA_CODE, '^[0-9]+$') AND ar.AREA_CD = TO_NUMBER(ci.AREA_CODE)
    JOIN GEO_HIERARCHY g ON g.BRNCH = 2 AND g.GEO_LEVEL = 4 AND g.SOURCE_TABLE = 'AREA' AND g.LEGACY_CODE = TO_CHAR(ar.AREA_DOC)
   WHERE ci.BRNCH = 2) x
ON (c.BRNCH = 2 AND c.CUSTOMER_CODE = x.CUSTOMER_CODE)
WHEN MATCHED THEN UPDATE SET c.GEO_CODE = x.GEO_CODE, c.GEO_SOURCE = 'ISB_AREA'
 WHERE NVL(c.GEO_SOURCE, '-') <> 'MANUAL';

PROMPT ISB customers whose area code does not exist <- their territory (area level of the new tree)
MERGE INTO CUSTOMER_INFO c
USING (
  SELECT ci.CUSTOMER_CODE, g.GEO_CODE
    FROM CUSTOMER_INFO ci
    JOIN GEO_HIERARCHY g ON g.BRNCH = 2 AND g.GEO_LEVEL = 3 AND g.LEGACY_CODE = ci.ZONE_CODE || '.' || ci.TERRITORY_CODE
   WHERE ci.BRNCH = 2
     AND NVL(ci.GEO_SOURCE, '-') NOT IN ('ISB_AREA', 'MANUAL')) x
ON (c.BRNCH = 2 AND c.CUSTOMER_CODE = x.CUSTOMER_CODE)
WHEN MATCHED THEN UPDATE SET c.GEO_CODE = x.GEO_CODE, c.GEO_SOURCE = 'ISB_TERRITORY';
COMMIT;

-- ---- 5. checks ----------------------------------------------------------------
SET PAGESIZE 500 LINESIZE 200
COLUMN chk FORMAT A60
PROMPT === nodes per branch and level vs legacy source (DIFF must be 0) ===
SELECT x.*, src_rows - tree_rows diff FROM (
SELECT 'KHI L1 zone      <- MASTER_AREA + missing M_AREA_CD' chk,
       (SELECT COUNT(*) FROM MASTER_AREA WHERE BRNCH = 1) + (SELECT COUNT(DISTINCT a.M_AREA_CD) FROM AREA a WHERE a.BRNCH = 1 AND NOT EXISTS (SELECT 1 FROM MASTER_AREA m WHERE m.BRNCH = 1 AND m.M_AREA_CD = a.M_AREA_CD)) src_rows,
       (SELECT COUNT(*) FROM GEO_HIERARCHY WHERE BRNCH = 1 AND GEO_LEVEL = 1) tree_rows FROM dual
UNION ALL SELECT 'KHI L2 territory <- AREA', (SELECT COUNT(*) FROM AREA WHERE BRNCH = 1), (SELECT COUNT(*) FROM GEO_HIERARCHY WHERE BRNCH = 1 AND GEO_LEVEL = 2) FROM dual
UNION ALL SELECT 'KHI L3 area      <- DISTRICT', (SELECT COUNT(*) FROM DISTRICT WHERE BRNCH = 1), (SELECT COUNT(*) FROM GEO_HIERARCHY WHERE BRNCH = 1 AND GEO_LEVEL = 3) FROM dual
UNION ALL SELECT 'KHI L4 city      <- CITY + CITY_V_TAB extras',
       (SELECT COUNT(*) FROM CITY WHERE BRNCH = 1) + (SELECT COUNT(*) FROM CITY_V_TAB v WHERE v.BRNCH = 1 AND NOT EXISTS (SELECT 1 FROM CITY c WHERE c.BRNCH = 1 AND c.AREA_CD = v.AREA_CD AND c.DIST_CD = v.DIST_CD AND c.CITY_CD = v.CITY_CD)),
       (SELECT COUNT(*) FROM GEO_HIERARCHY WHERE BRNCH = 1 AND GEO_LEVEL = 4) FROM dual
UNION ALL SELECT 'ISB L1 zone      <- ZONE_DESC (copy)', (SELECT COUNT(*) FROM ZONE_DESC WHERE BRNCH = 2), (SELECT COUNT(*) FROM GEO_HIERARCHY WHERE BRNCH = 2 AND GEO_LEVEL = 1) FROM dual
UNION ALL SELECT 'ISB L2 territory <- ZONE_DESC', (SELECT COUNT(*) FROM ZONE_DESC WHERE BRNCH = 2), (SELECT COUNT(*) FROM GEO_HIERARCHY WHERE BRNCH = 2 AND GEO_LEVEL = 2) FROM dual
UNION ALL SELECT 'ISB L3 area      <- TERRITORY', (SELECT COUNT(*) FROM TERRITORY WHERE BRNCH = 2), (SELECT COUNT(*) FROM GEO_HIERARCHY WHERE BRNCH = 2 AND GEO_LEVEL = 3) FROM dual
UNION ALL SELECT 'ISB L4 city      <- AREA', (SELECT COUNT(*) FROM AREA WHERE BRNCH = 2), (SELECT COUNT(*) FROM GEO_HIERARCHY WHERE BRNCH = 2 AND GEO_LEVEL = 4) FROM dual
UNION ALL SELECT 'ERR$_GEO_HIERARCHY rows (must be 0)', 0, (SELECT COUNT(*) FROM ERR$_GEO_HIERARCHY) FROM dual
) x;

PROMPT === LEGACY_MAP rows per entity ===
SELECT BRNCH, ENTITY, COUNT(*) n FROM LEGACY_MAP GROUP BY BRNCH, ENTITY ORDER BY 1, 2;

PROMPT === customers placed ===
SELECT BRNCH, NVL(GEO_SOURCE, '(not placed)') geo_source, COUNT(*) n FROM CUSTOMER_INFO GROUP BY BRNCH, NVL(GEO_SOURCE, '(not placed)') ORDER BY 1, 2;

PROMPT === nodes that need a business check (REMARKS) ===
SELECT BRNCH, GEO_CODE, ZONE_NAME, TERRITORY_NAME, CITY_NAME, REMARKS FROM GEO_HIERARCHY WHERE REMARKS IS NOT NULL AND NOT (BRNCH = 2 AND GEO_LEVEL = 1) ORDER BY 1, 2;
