-- =====================================================================
--  01_DCL_SALES_TABLES.sql
--  DEWAN CEMENT LIMITED - UNIFIED SALES DATABASE (Karachi + Islamabad)
--  Built from SALES@LOCALSDB (KHI, 245 tables) and SCLSALES@ISB.WORLD (ISB, 123 tables).
--
--  LOSSLESS DESIGN - every row of every business table of both DBs fits:
--  * Names follow Karachi. Each table has the UNION of KHI and ISB columns.
--  * Every column is wide enough for the largest KHI/ISB value
--    (checked column by column by the generator - 0 problems).
--  * NOT NULL only where the column is NOT NULL in BOTH DBs.
--  * NO EXTRA COLUMNS: a table never has more columns than its KHI or ISB
--    table. Columns that mean the same thing under two names are ONE column
--    (Karachi name kept), filled from the branch's own column:
--      AREA: AREA_CD = AREA_CODE, AREA_NAME = AREA_DESC
--      TARGET_MST: SERNO = TRG_NO, REMRK = DESCR
--      SALES_REQUEST_MASTER: TRANSPORTER_2 = TRANSPORTER, BAG_CD = BAGTYP
--      BAG = KHI BAG + ISB BAGS_MASTER (BAG_CD = SERNO, BAG_DESC = DESCR)
--      CASH_CHEQUE_RECEIPTS: CANCEL_STATS = STATUS
--  * VARCHAR2/CHAR sizes are the larger of the KHI and ISB size, never more.
--    Customer codes are 11 everywhere (KHI 7, ISB 11) so every table can hold both branches' customers.
--  * Every table has BRNCH (1 = Karachi, 2 = Islamabad) and COMPC.
--    BRNCH is the first column of every natural primary key, so the same
--    customer / DC / BRV number from both DBs never collides.
--  * A table gets its natural primary key ONLY if that key is a primary key
--    in every source DB (so it is guaranteed unique and not null).
--    Otherwise it has no primary key (no surrogate ID column is added); its
--    business key is added by 03_DCL_SALES_KEYS_AFTER_LOAD.sql with ENABLE
--    NOVALIDATE: old rows are never rejected, new rows are checked.
--  * No foreign keys in this file - all are in script 03 (after the load).
--  * One table per legacy table name: KHI FH_DELIVERY_CHALLAN, FH_DEL_CHALLAN_DETAIL,
--    FH_DELIVERY_MEMO, FH_DC_DOCUMENT stay separate from the *_OLD tables.
--  * Section 9 keeps the old structures that the new design replaces, so
--    their history is not lost. Backups, test, demo, tool and report-staging
--    tables are not created: keep the full legacy import (archive schemas
--    used by script 02) - nothing is ever deleted.
--  * Oracle 11g compatible: no identity columns, all names <= 30 characters.
--
--  Run order: 01 (this) -> 02_DCL_SALES_LOAD_DATA.sql -> 03_DCL_SALES_KEYS_AFTER_LOAD.sql
-- =====================================================================
