-- =====================================================================
--  02c_LOAD_LEGACY_EXTRA.sql   (run as SALES_NEW after 02 or 02_LOAD_TRANSACTIONS_ONLY
--                               and after migrations/001_LEGACY_TABLES_NOT_HOSTED.sql)
--  Loads what the 19-Nov-2026 column-by-column audit found missing:
--   A. legacy business tables that 01 had no home for (tables created by migrations/001)
--   B. rows that exist ONLY in legacy backup copies, rescued into their real table
--   C. columns that are empty in legacy but derivable from the parent row
--  Window: same DEFINEs as 02_LOAD_TRANSACTIONS_ONLY. FULL_LOAD = Y loads all history
--  (rows whose date is empty are then included as well).
--  Re-runnable: A tables are emptied first; B rows are inserted only when not present.
--  Every insert logs failures to ERR$_<table>; the reconciliation at the end must show
--  DIFF = 0 and ERR_ROWS = 0.
--  Generated from the real column lists (DESCRIBE of SCLKHI / SCLISB / SALES_NEW).
-- =====================================================================
SET DEFINE ON
SET VERIFY OFF
SET ECHO ON
SET TIMING ON
WHENEVER SQLERROR EXIT
SELECT CASE WHEN USER = 'SALES_NEW' THEN 'OK: connected as SALES_NEW' ELSE TO_CHAR(1/0) END AS user_check FROM dual;
WHENEVER SQLERROR CONTINUE
DEFINE KHI_SCH   = SCLKHI
DEFINE ISB_SCH   = SCLISB
DEFINE FROM_DT   = 01-09-2026
DEFINE TO_DT     = 01-10-2026
DEFINE FULL_LOAD = N

