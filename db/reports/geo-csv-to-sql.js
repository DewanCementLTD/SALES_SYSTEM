// Turns a customer geography list filled in by Sales into a reviewable SQL script.
//
//   node geo-csv-to-sql.js KHI_ACTIVE_CUSTOMERS_WITHOUT_GEO.csv > 02e_LOAD_MANUAL_GEO.sql
//
// Input: the CSV exported by the data check (first column CUSTOMER_CODE, last column NEW_GEO_CODE).
// Rows with an empty NEW_GEO_CODE are skipped. Output: one UPDATE per customer, Karachi only
// (BRNCH 1), GEO_SOURCE = 'MANUAL', guarded so a GEO_CODE that is not in GEO_HIERARCHY changes nothing,
// followed by a check that lists codes that did not match. Run the output in SQL*Plus as SALES_NEW.
import { readFileSync } from 'node:fs';

/** @param {string} line */
function parseCsvLine(line) {
  const out = [];
  let cur = '';
  let quoted = false;
  for (let i = 0; i < line.length; i++) {
    const ch = line[i];
    if (quoted) {
      if (ch === '"' && line[i + 1] === '"') { cur += '"'; i++; }
      else if (ch === '"') quoted = false;
      else cur += ch;
    } else if (ch === '"') quoted = true;
    else if (ch === ',') { out.push(cur); cur = ''; }
    else cur += ch;
  }
  out.push(cur);
  return out.map((s) => s.trim());
}

const file = process.argv[2];
if (!file) {
  console.error('usage: node geo-csv-to-sql.js <filled csv>');
  process.exit(1);
}
const lines = readFileSync(file, 'utf8').split(/\r?\n/).filter((l) => l.trim() !== '');
const header = parseCsvLine(lines[0]);
const iCode = 0;
const iGeo = header.length - 1;
const safe = /^[A-Za-z0-9\-.]+$/;
const rows = [];
for (const line of lines.slice(1)) {
  const f = parseCsvLine(line);
  const code = f[iCode];
  const geo = f[iGeo];
  if (!geo) continue;
  if (!safe.test(code) || !safe.test(geo)) {
    console.error(`skipped (unexpected characters): ${code} -> ${geo}`);
    continue;
  }
  rows.push([code, geo]);
}

const sql = [
  '-- generated by db/reports/geo-csv-to-sql.js from ' + file.replace(/\\/g, '/'),
  'SET DEFINE OFF',
  'WHENEVER SQLERROR EXIT',
  "SELECT CASE WHEN USER = 'SALES_NEW' THEN 'OK: connected as SALES_NEW' ELSE TO_CHAR(1/0) END AS user_check FROM dual;",
  'WHENEVER SQLERROR CONTINUE',
  ...rows.map(([c, g]) =>
    `UPDATE CUSTOMER_INFO SET GEO_CODE = '${g}', GEO_SOURCE = 'MANUAL' WHERE BRNCH = 1 AND CUSTOMER_CODE = '${c}' AND EXISTS (SELECT 1 FROM GEO_HIERARCHY g WHERE g.BRNCH = 1 AND g.GEO_CODE = '${g}');`),
  'COMMIT;',
  "PROMPT === rows from the file that were NOT applied (unknown customer or GEO_CODE) ===",
  'SELECT x.code, x.geo FROM (',
  rows.map(([c, g]) => `  SELECT '${c}' code, '${g}' geo FROM dual`).join('\n  UNION ALL\n') || "  SELECT NULL code, NULL geo FROM dual WHERE 1 = 0",
  ') x WHERE NOT EXISTS (SELECT 1 FROM CUSTOMER_INFO c WHERE c.BRNCH = 1 AND c.CUSTOMER_CODE = x.code AND c.GEO_CODE = x.geo);',
];
process.stdout.write(sql.join('\n') + '\n');
console.error(`${rows.length} customers in the script`);
