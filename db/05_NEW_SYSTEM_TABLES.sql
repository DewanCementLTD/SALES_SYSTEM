-- =====================================================================
--  05_NEW_SYSTEM_TABLES.sql
--  DCL Sales & Dispatch - tables and columns the new application needs
--  on top of the unified legacy-named schema (01 -> 02 -> 03 -> 04).
--
--  * Oracle 11g compatible (no identity columns, no 12c syntax, names <= 30).
--  * Technical ids of NEW tables come from sequences (SEQ_<table>), used by
--    the application as SEQ_X.NEXTVAL in the INSERT. Document NUMBERS never
--    use sequences: they come from DOC_SEQUENCE (gap-free, BR-NUM-01).
--  * Legacy tables are only EXTENDED (ADD columns, widen a column). Nothing is
--    renamed or dropped. Column adds are re-runnable (ORA-01430 ignored).
--  * New CREATE TABLE statements are meant to run once. Re-running them gives
--    ORA-00955 (name already used) and changes nothing.
--
--  Run as the schema owner (e.g. SALES_NEW) in SQL*Plus, after 01-04:
--    SPOOL run_05.log
--    @05_NEW_SYSTEM_TABLES.sql
--    SPOOL OFF
--  Spec: docs/SCHEMA.md
-- =====================================================================
SET DEFINE OFF
WHENEVER SQLERROR EXIT
-- safety: never run as SYS/SYSTEM
SELECT CASE WHEN USER IN ('SYS','SYSTEM') THEN TO_CHAR(1/0) ELSE 'OK: running as '||USER END AS user_check FROM dual;
WHENEVER SQLERROR CONTINUE

